#11.solicite base e altura de um retângulo. calcule a sua área e seu perimetro

#entrada
base=float(input("Qual a base do retangulo em cm: "))

altura=float(input("qual a altura do retangulo em cm: "))


#processamento
area=base*altura
perimetro=(2*base)+(2*altura)

#saida
print(f"a area do triangulo é {area} cm quadrados")

print(f"o perimetro do triangulo é {perimetro} cm ")